GGC_Helper::~GGC_Helper()
{
	m_errorMessages.clear();
	m_approvableErrors.clear();
	m_criticalErrors.clear();
}

bool GGC_Helper::StackError(unsigned long error, bool bCritical)
{
	if (error == NPGAMEMON_SUCCESS)
		return false;

	if (bCritical)
	{
		switch (error)
		{
		case NPGAMEMON_ERROR_EXIST:
		case NPGAMEMON_ERROR_GAME_EXIST:
		case NPGAMEMON_ERROR_INIT:
		case NPGAMEMON_ERROR_AUTH_GAMEGUARD:
		case NPGAMEMON_ERROR_NFOUND_GAMEMON:
		case NPGAMEMON_ERROR_AUTH_INI:
		case NPGAMEMON_ERROR_NFOUND_INI:
		case NPGAMEMON_ERROR_CRYPTOAPI:
		case NPGAMEMON_ERROR_EXECUTE:
		case NPGAMEMON_ERROR_ILLEGAL_PRG:
		case NPGMUP_ERROR_ABORT:
		case NPGMUP_ERROR_CONNECT:
		case NPGMUP_ERROR_DOWNCFG:
		case NPGMUP_ERROR_AUTH:
		case NPGAMEMON_ERROR_NPSCAN:
			return StackCriticalError(error);
		default:
			return StackCriticalError(error);
		}
	}

	switch (error)
	{
	case NPGAMEMON_COMM_ERROR:
	case NPGAMEMON_COMM_CLOSE:
	case NPGAMEMON_INIT_ERROR:
	case NPGAMEMON_SPEEDHACK:
	case NPGAMEMON_GAMEHACK_KILLED:
	case NPGAMEMON_GAMEHACK_DETECT:
	case NPGAMEMON_GAMEHACK_DOUBT:
		return StackCriticalError(error);
	default:
		return true;
	}
}

bool GGC_Helper::StackApprovableError(unsigned long error)
{
	m_approvableErrors.push_back(error);

	return true;
}

bool GGC_Helper::StackCriticalError(unsigned long error)
{
	m_criticalErrors.push_back(error);

	if (g_pFresh == NULL)
	{
		ForceShutdown();
		std::string message;
		GetErrorMessage(error, message);
		MessageBox(NULL, message.c_str(), "PangYa", MB_OK);
	}
	else if (m_pDlg == NULL)
	{
		m_pDlg = CreateForm<GGC_Dlg>(g_pFresh->GetManager(), this, "GameGuard",
			NULL);

		if (m_pDlg == NULL)
			ForceShutdown();

		m_pDlg->Open((FRESH_PFN_RESULT)&GGC_Helper::OnGameGuardDlgResult,
			FrRET_OK | FrEXCLUSIVE);
	}
	else
	{
		ForceShutdown();
	}

	return false;
}

void GGC_Helper::GetErrorMessage(unsigned long error, std::string& message)
{
	if (m_errorMessages.find(error) != m_errorMessages.end())
	{
		message = m_errorMessages[error];
		return;
	}

	ADD_ERROR_MESSAGE(error,
		K2L_Compatibility("\xb0\xd4\xc0\xd3\xb0\xa1\xb5\xe5 \xbd\xc7\xc7\xe0 \xc1\xdf \xbf\xa1\xb7\xaf\xb0\xa1 \xb9\xdf\xbb\xfd\xc7\xcf\xbf\xb4\xbd\xc0\xb4\xcf\xb4\xd9. \xb0\xd4\xc0\xd3 \xc6\xfa\xb4\xf5 \xbe\xc8\xc0\xc7 GameGuard \xc6\xfa\xb4\xf5\xbf\xa1 \xc0\xd6\xb4\xc2 *.erl \xc6\xc4\xc0\xcf\xb5\xe9\xc0\xbb game1@inca.co.kr\xb7\xce \xc3\xb7\xba\xce\xc7\xcf\xbf\xa9 \xb8\xde\xc0\xcf \xba\xb8\xb3\xbb\xc1\xd6\xbd\xc3\xb1\xe2 \xb9\xd9\xb6\xf8\xb4\xcf\xb4\xd9"));
	GetErrorMessage(error, message);
}

bool GGC_Helper::GetFirstCriticalErrorMessage(unsigned long& error,
	std::string& message)
{
	if (GetCriticalErrorCount() == 0)
		return false;

	error = m_criticalErrors.front();
	GetErrorMessage(error, message);

	return true;
}

void GGC_Helper::ForceShutdown()
{
	g_bQuit = true;

	if (WNetworkSystem::IsInstantiated() &&
		WNetworkSystem::Instance()->IsConnected(WNetworkSystem::NET_GAME))
		WNetworkSystem::Instance()->ForceShutDown(WNetworkSystem::NET_GAME);

	if (WNetworkSystem::IsInstantiated() &&
		WNetworkSystem::Instance()->IsConnected(WNetworkSystem::NET_LOGIN))
		WNetworkSystem::Instance()->ForceShutDown(WNetworkSystem::NET_LOGIN);
}

void GGC_Helper::Reset()
{
	m_approvableErrors.clear();
	m_criticalErrors.clear();
}

bool GGC_Helper::OnGameGuardDlgResult(int result, FrForm* form)
{
	ForceShutdown();

	return true;
}
